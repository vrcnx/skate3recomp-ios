#!/usr/bin/env python3
"""Generate a stand-in for rexglue's generated/ output so the app can be built
and its platform layer (window, Vulkan/MoltenVK, ImGui, input, ISO install
wizard) exercised without a Skate 3 dump.

The stub declares every guest function the hand-written sources reference,
gives each a no-op body (the sources' strong overrides still win over the weak
defaults) and empty function tables. A shell build can never boot the game:
it stops at the install wizard. Use the real generate-all output for that.

usage: make_shell_stub.py <repo root> <output dir>
"""
import pathlib
import re
import sys

root = pathlib.Path(sys.argv[1]).resolve()
out = pathlib.Path(sys.argv[2]).resolve()
templates = root / "third_party/rexglue-sdk/resources/templates/codegen"

names = set()
for path in (root / "src").rglob("*"):
    if path.suffix in {".cpp", ".h", ".mm"}:
        names.update(re.findall(r"\b(?:__imp__)?(sub_[0-9A-Fa-f]{8}|__(?:save|rest)[a-z]+_[0-9]+)\b", path.read_text(errors="ignore")))
names = sorted(names)


def render_init_h(project):
    text = (templates / "init_h.inja").read_text()
    text = re.sub(r'\{% include "codegen/(\w+)\.inja" %\}',
                  lambda m: (templates / f"{m.group(1)}.inja").read_text(), text)
    # Every codegen config flag off: the stub has no recompiled bodies.
    text = re.sub(r"\{% if config_flags\.\w+ %\}.*?\{% endif %\}", "", text, flags=re.S)
    text = text.replace("{% if rexcrt_heap %}1{% else %}0{% endif %}", "0")
    for key in ("image_base", "image_size", "code_base", "code_size", "thunk_reserve_size"):
        text = text.replace("{{ %s }}" % key, "0")
    text = text.replace("{{ project }}", project)
    decls = "".join(f"DECLARE_REX_FUNC({n});\n" for n in names) if project == "skate3" else ""
    text = re.sub(r"\{% for fn in functions %\}.*?\{% endfor %\}", decls, text, flags=re.S)
    leftover = re.findall(r"\{[{%].*?[%}]\}", text)
    if leftover:
        sys.exit(f"unrendered template syntax in init_h: {leftover[:3]}")
    return text


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


header = "// Generated by ios/tools/make_shell_stub.py - shell build only, no game code\n"
for project, subdir in (("skate3", ""), ("eawebkit", "eawebkit/")):
    write(out / f"{subdir}{project}_init.h", render_init_h(project))
    body = header + f'#include "{project}_init.h"\n\n'
    body += f"PPCFuncMapping {project}_PPCFuncMappings[] = {{{{0, nullptr}}}};\n"
    body += f"const rex::PPCImageInfo {project}_PPCImageConfig = {{\n"
    body += f"    .func_mappings = {project}_PPCFuncMappings,\n}};\n"
    if project == "skate3":
        for n in names:
            body += f"\nREX_EXTERN(__imp__{n}) {{}}\nextern \"C\" REX_WEAK_FUNC({n}) {{ __imp__{n}(ctx, base); }}\n"
    write(out / f"{subdir}{project}_init.cpp", body)
    write(out / f"{subdir}sources.cmake",
          f'set(GENERATED_SOURCES "${{CMAKE_CURRENT_LIST_DIR}}/{project}_init.cpp")\n')
print(f"shell stub: {len(names)} guest functions -> {out}")
